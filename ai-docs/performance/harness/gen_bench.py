"""Generates a synthetic rules_flutter benchmark workspace.

    gen_bench.py <out> <packages> <files_per_package> <rules_flutter checkout>
                 [--rules-dart <rules_dart checkout>] [--no-format]

N packages packages/pkgI, each a flutter_library with F files under lib/src/.
pkgI depends on pkg(I-1) and pkg(I-2). Each file defines a StatelessWidget and
a plain `int valueI x F()` function. Each package has one flutter_test (a
testWidgets case that pumps a MaterialApp around one of its widgets). app/ holds
a flutter_kernel_target and a flutter_web_app for the last package, plus a
flutter_application and flutter_linux_app when they build on this host.

After writing, the workspace is fetched (`bazel build //... --nobuild`) and its
Dart files are formatted with the Flutter SDK's own `dart format`, so the
dart_format check passes. `--no-format` skips that step.

Adapted from rules_dart's harness gen_bench.py.
"""
import argparse, glob, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def w(out, path, text):
    p = os.path.join(out, path)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(text)


def module_bazel(rules, rules_dart_given):
    return f'''module(name = "rules_flutter_bench")

bazel_dep(name = "rules_flutter", version = "0.0.0")
bazel_dep(name = "rules_dart", version = "0.7.2")
bazel_dep(name = "bazel_skylib", version = "1.9.2")
bazel_dep(name = "platforms", version = "1.1.0")

local_path_override(
    module_name = "rules_flutter",
    path = "{rules}",
)

flutter = use_extension("@rules_flutter//flutter:extensions.bzl", "flutter")
flutter.toolchain(flutter_version = "3.47.6")
flutter.pub(
    name = "deps",
    lock = "//:pubspec.lock",
)
use_repo(flutter, "deps", "flutter_toolchains", "flutter_web_sdk")

register_toolchains("@flutter_toolchains//:all")
'''


def bench_jobs():
    """Bazel --jobs for the generated workspace: env RULES_FLUTTER_BENCH_JOBS, default 8.

    Lower it on a memory-capped host (Flutter kernel compiles are memory-heavy);
    compare only results recorded with the same value (the suite writes it to `jobs`).
    """
    return int(os.environ.get("RULES_FLUTTER_BENCH_JOBS", "8"))


def bazelrc(rules_dart_path):
    lines = [
        "# Generated by gen_bench.py (rules_flutter benchmark workspace).",
        "startup --host_jvm_args=-Xmx4g",
        f"common --jobs={bench_jobs()}",
        "common --lockfile_mode=off",
    ]
    if rules_dart_path:
        lines.append(f"common --override_module=rules_dart={rules_dart_path}")
    lines += [
        "",
        "build:lint --aspects=@rules_dart//dart:analyze.bzl%dart_analyze",
        "build:lint --output_groups=+dart_analyze",
        "build:lint --output_groups=+dart_format",
        "common --@rules_dart//dart:analysis_config=//:analysis_config",
        "try-import %workspace%/.bazelrc.user",
        "",
    ]
    return "\n".join(lines)


ANALYSIS_OPTIONS = "analyzer:\n  language:\n    strict-casts: true\n"


def lib_file(p, f, deps):
    imports = "".join(f"import 'package:pkg{d}/pkg{d}.dart';\n" for d in deps)
    body = "  var total = %d;\n" % (f + 1)
    for d in deps:
        body += f"  total += value{d}x0();\n"
    return f'''import 'package:flutter/material.dart';
{imports}
/// Widget {f} of package pkg{p}.
class W{p}x{f} extends StatelessWidget {{
  /// Creates the widget.
  const W{p}x{f}({{super.key, this.value = 0}});

  /// The number shown.
  final int value;

  @override
  Widget build(BuildContext context) {{
    return Text('pkg{p} f{f}: $value ${{value{p}x{f}()}}');
  }}
}}

/// Plain value of file {f} of package pkg{p}.
int value{p}x{f}() {{
{body}  return total;
}}
'''


def test_file(p):
    return f'''import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:pkg{p}/pkg{p}.dart';

void main() {{
  testWidgets('W{p}x0 renders in a MaterialApp', (tester) async {{
    await tester.pumpWidget(
      const MaterialApp(home: Scaffold(body: W{p}x0(value: 1))),
    );
    expect(find.byType(W{p}x0), findsOneWidget);
    expect(value{p}x0(), greaterThan(0));
  }});
}}
'''


def package_build(p, deps):
    dep_lines = "".join(f'        "//packages/pkg{d}",\n' for d in deps)
    return f'''load("@rules_flutter//flutter:defs.bzl", "flutter_library", "flutter_test")

flutter_library(
    name = "pkg{p}",
    package_name = "pkg{p}",
    srcs = glob(["lib/**/*.dart"]),
    visibility = ["//visibility:public"],
    deps = [
{dep_lines}        "@deps//:flutter",
    ],
)

flutter_test(
    name = "pkg{p}_test",
    package_name = "pkg{p}",
    main = "test/pkg{p}_test.dart",
    srcs = glob(["lib/**/*.dart"]),
    deps = [
{dep_lines}        "@deps//:flutter",
        "@deps//:flutter_test",
    ],
)
'''


def app_build(last):
    return f'''load("@rules_flutter//flutter:defs.bzl", "flutter_application", "flutter_kernel_target")
load("@rules_flutter//flutter:linux.bzl", "flutter_linux_app")
load("@rules_flutter//flutter:web.bzl", "flutter_web_app")

flutter_kernel_target(
    name = "app_kernel",
    package_name = "app",
    srcs = ["lib/main.dart"],
    main = "lib/main.dart",
    deps = [
        "//packages/pkg{last}",
        "@deps//:flutter",
    ],
)

flutter_web_app(
    name = "app_web",
    package_name = "app",
    app_name = "Bench App",
    main = "lib/main.dart",
    srcs = ["lib/main.dart"],
    deps = [
        "//packages/pkg{last}",
        "@deps//:flutter",
    ],
)

flutter_application(
    name = "app",
    package_name = "app",
    main = "lib/main.dart",
    srcs = ["lib/main.dart"],
    deps = [
        "//packages/pkg{last}",
        "@deps//:flutter",
    ],
)

flutter_linux_app(
    name = "app_linux",
    application = ":app",
    gtk_app_id = "com.example.rulesflutterbench",
    target_compatible_with = ["@platforms//os:linux"],
)
'''


APP_MAIN = '''import 'package:flutter/material.dart';
import 'package:pkg{last}/pkg{last}.dart';

void main() {{
  runApp(
    const MaterialApp(
      home: Scaffold(body: Center(child: W{last}x0(value: 1))),
    ),
  );
}}
'''


def generate(out, n_pkgs, n_files, rules, rules_dart=None, output_base=None):
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    if output_base:
        # Read by every bazel call in this workspace, including the fetch below.
        w(out, ".bazelrc.user", f"startup --output_base={output_base}\n")
    last = n_pkgs - 1
    w(out, "MODULE.bazel", module_bazel(rules, rules_dart is not None))
    # hello_world's lock: web_example's has no flutter_test entry, which the tests need.
    e2e = os.path.join(rules, "e2e", "hello_world")
    shutil.copy(os.path.join(e2e, "pubspec.lock"), os.path.join(out, "pubspec.lock"))
    shutil.copy(os.path.join(e2e, "pubspec.yaml"), os.path.join(out, "pubspec.yaml"))
    w(out, ".bazelrc", bazelrc(rules_dart))
    w(out, ".bazelversion", open(os.path.join(rules, ".bazelversion")).read())
    w(out, "analysis_options.yaml", ANALYSIS_OPTIONS)
    w(out, "BUILD.bazel", '''load("@rules_dart//dart:defs.bzl", "dart_analysis_config", "dart_analysis_options")

exports_files(["pubspec.lock"])

dart_analysis_options(name = "options", src = "analysis_options.yaml")

dart_analysis_config(name = "analysis_config", options = [":options"])
''')
    for p in range(n_pkgs):
        deps = [d for d in (p - 1, p - 2) if d >= 0]
        for f in range(n_files):
            w(out, f"packages/pkg{p}/lib/src/f{f}.dart", lib_file(p, f, deps))
        exports = "".join(f"export 'src/f{f}.dart';\n" for f in range(n_files))
        w(out, f"packages/pkg{p}/lib/pkg{p}.dart",
          f"/// Public API of package pkg{p}.\n" + exports)
        w(out, f"packages/pkg{p}/test/pkg{p}_test.dart", test_file(p))
        w(out, f"packages/pkg{p}/BUILD.bazel", package_build(p, deps))
    w(out, "app/lib/main.dart", APP_MAIN.format(last=last))
    w(out, "app/BUILD.bazel", app_build(last))


def sdk_dart(out):
    """The Flutter SDK's dart binary, from the output base of an analysed workspace."""
    ob = subprocess.run(["bazel", "info", "output_base"], cwd=out, capture_output=True,
                        text=True, check=True).stdout.strip()
    hits = glob.glob(os.path.join(ob, "external", "*flutter*", "dart-sdk", "bin", "dart"))
    hits.sort(key=lambda h: ("linux-x64" not in h, h))
    if not hits:
        raise SystemExit("no Flutter SDK dart under " + ob + "/external")
    return hits[0]


def format_workspace(out):
    r = subprocess.run(["bazel", "build", "//...", "--nobuild"], cwd=out,
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit("fetch failed:\n" + (r.stdout + r.stderr)[-3000:])
    dart = sdk_dart(out)
    home = os.path.join(out, "..", os.path.basename(out) + "_home_fmt")
    os.makedirs(home, exist_ok=True)
    env = dict(os.environ, HOME=os.path.abspath(home))
    r = subprocess.run([dart, "format", "packages", "app"], cwd=out, env=env,
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit("dart format failed:\n" + (r.stdout + r.stderr)[-3000:])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("out")
    ap.add_argument("packages", type=int)
    ap.add_argument("files_per_package", type=int)
    ap.add_argument("rules_flutter")
    ap.add_argument("--rules-dart", default=None)
    ap.add_argument("--no-format", action="store_true")
    ap.add_argument("--output-base", default=None,
                    help="Bazel output base for this workspace, written to .bazelrc.user")
    a = ap.parse_args()
    rules = os.path.abspath(a.rules_flutter)
    rules_dart = os.path.abspath(a.rules_dart) if a.rules_dart else None
    out = os.path.abspath(a.out)
    generate(out, a.packages, a.files_per_package, rules, rules_dart, a.output_base)
    if not a.no_format:
        format_workspace(out)
    print("generated", out)


if __name__ == "__main__":
    sys.exit(main())
