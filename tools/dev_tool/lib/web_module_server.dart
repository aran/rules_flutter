  /// Parse DDC manifest and extract modules, source maps, and metadata.
  ///
  /// DDC frontend server writes incremental output to the same files,
  /// containing only changed modules. We merge into existing state so
  /// unchanged modules remain available.
  ///
  /// Throws [DevToolException] when the compiler reported success and its
  /// output does not back that up: a missing artifact, a manifest that does
  /// not parse, or offsets that do not fit the file they index into. A silent
  /// `return` or a skipped module for any of those shows up only as a page
  /// that 404s its way to a blank screen (first compile) or an edit that
  /// reports as reloaded and is not on screen (later compiles).
  ///
  /// The throw is the report. On the first compile it unwinds through
  /// `run_command` to `bin/flutter_bazel.dart` and ends the run; from a reload
  /// `session.dart` catches it and renders it as the reload's diagnostics.
  ///
  /// Upstream reads all four artifacts unguarded (`memory_fs.dart:29-34`), so
  /// a missing one throws there too; where it differs is skipping a module
  /// whose offsets do not fit (`memory_fs.dart:40-48`). Skipping is what makes
  /// the failure invisible, so we report instead.
  void updateModules(String dillPath, {required bool full}) {
    final manifestFile = File('$dillPath.json');
    final sourcesFile = File('$dillPath.sources');
    final mapFile = File('$dillPath.map');
    final metadataFile = File('$dillPath.metadata');

    if (!manifestFile.existsSync()) {
      throw DevToolException(
        _missingArtifact(
          manifestFile.path,
          dillPath,
          'the manifest naming every module the page loads',
        ),
      );
    }
    if (!sourcesFile.existsSync()) {
      throw DevToolException(
        _missingArtifact(
          sourcesFile.path,
          dillPath,
          'the JavaScript that the manifest slices each module out of',
        ),
      );
    }

    final Map<String, dynamic> manifest;
    try {
      manifest =
          json.decode(manifestFile.readAsStringSync()) as Map<String, dynamic>;
    } catch (e) {
      throw DevToolException(
        'The DDC module manifest ${manifestFile.path} is not a JSON object '
        'of module offsets: $e\n'
        'Nothing from this compile can be served.',
      );
    }
    final sourcesBytes = sourcesFile.readAsBytesSync();
    final mapBytes = mapFile.existsSync() ? mapFile.readAsBytesSync() : null;
    final metadataBytes = metadataFile.existsSync()
        ? metadataFile.readAsBytesSync()
        : null;

    // A full compile produces the whole program, so what it does not name is
    // no longer part of it — the description is rebuilt rather than added to,
    // or a module a recompile dropped lingers in the list a fresh page loads
    // and the page fetches a script the server no longer has.
    //
    // Only the description. The byte stores ([_modules], [_metadata],
    // [_sourcemaps]) keep merging: nothing can request what the description
    // does not name, so bytes left behind by a superseded compile are
    // unreachable rather than wrong, and clearing them would stake the page's
    // boot on a full compile never omitting anything.
    if (full) {
      _metadataByModule.clear();
    }

    // Merge into existing state — incremental compiles only contain changed
    // modules, and unchanged modules must remain available.
    final reloadedSources = <Map<String, dynamic>>[];
    final digests = <String, String>{if (!full) ..._moduleDigests};
    // Modules the compiler described without usable metadata. Collected and
    // reported once: with no metadata there is no library list, and
    // `$dartReloadModifiedModules` reloads modules by library — so an edit in
    // one of these reports as reloaded and does not take effect. Per-module
    // warnings would be one line per module in the app.
    final withoutMetadata = <String>[];

    for (final entry in manifest.entries) {
      var modulePath = entry.key;
      if (modulePath.startsWith('/')) {
        modulePath = modulePath.substring(1);
      }
      final rawOffsets = entry.value;
      if (rawOffsets is! Map<String, dynamic>) {
        throw DevToolException(
          'The DDC module manifest ${manifestFile.path} describes module '
          '${entry.key} with ${rawOffsets.runtimeType}, not a map of '
          'section offsets.',
        );
      }
      final offsets = rawOffsets;
      final moduleName = modulePath.replaceAll('.lib.js', '');

      // Code (JS source). Required: a manifest entry with no servable code is
      // a module request that 404s.
      _modules[modulePath] = _slice(
        sourcesBytes,
        offsets: offsets,
        section: 'code',
        module: moduleName,
        artifact: sourcesFile.path,
      );
      final reloadEntry = <String, dynamic>{
        'src': '${uri ?? ''}/$modulePath',
        'module': moduleName,
        'libraries': <String>[],
      };
      reloadedSources.add(reloadEntry);
      digests[moduleName] = _modules[modulePath]!.length.toRadixString(16);

      // Source maps. The manifest is the contract: a declared section whose
      // file is absent is inconsistent output, not an optional extra.
      if (offsets.containsKey('sourcemap')) {
        if (mapBytes == null) {
          throw DevToolException(
            _missingArtifact(
              mapFile.path,
              dillPath,
              'the source maps its manifest declares for module $moduleName',
            ),
          );
        }
        _sourcemaps['$modulePath.map'] = _slice(
          mapBytes,
          offsets: offsets,
          section: 'sourcemap',
          module: moduleName,
          artifact: mapFile.path,
        );
      }

      // Metadata (for DWDS module resolution).
      if (!offsets.containsKey('metadata')) {
        withoutMetadata.add(moduleName);
        continue;
      }
      if (metadataBytes == null) {
        throw DevToolException(
          _missingArtifact(
            metadataFile.path,
            dillPath,
            'the module metadata its manifest declares for module '
            '$moduleName',
          ),
        );
      }
      final metaSlice = _slice(
        metadataBytes,
        offsets: offsets,
        section: 'metadata',
        module: moduleName,
        artifact: metadataFile.path,
      );
      _metadata['$modulePath.metadata'] = metaSlice;
      final metaStr = utf8.decode(metaSlice);
      if (metaStr.isEmpty) {
        withoutMetadata.add(moduleName);
        continue;
      }
      _metadataByModule[modulePath] = metaStr;

      // Extract libraries from metadata for reloaded_sources.
      final Map<String, dynamic> metaJson;
      try {
        metaJson = json.decode(metaStr) as Map<String, dynamic>;
      } catch (e) {
        // Not survivable, and not only ours to survive: these same bytes go
        // into the merged metadata DWDS parses line by line, where a bad line
        // rethrows out of `MetadataProvider._processMetadata` with no module
        // named. Reported here it names one.
        throw DevToolException(
          _badMetadata(
            moduleName,
            metadataFile.path,
            'is not a JSON object: $e',
          ),
        );
      }
      // Use metadata name for module field when available.
      final metaName = metaJson['name'];
      if (metaName != null) {
        if (metaName is! String) {
          throw DevToolException(
            _badMetadata(
              moduleName,
              metadataFile.path,
              'names the module with ${json.encode(metaName)}, not a string',
            ),
          );
        }
        reloadEntry['module'] = metaName;
      }
      final libs = metaJson['libraries'];
      if (libs != null) {
        if (libs is! List) {
          throw DevToolException(
            _badMetadata(
              moduleName,
              metadataFile.path,
              'lists its libraries as ${json.encode(libs)}, not an array',
            ),
          );
        }
        final libraryUris = <String>[];
        for (final lib in libs) {
          if (lib is! Map) {
            throw DevToolException(
              _badMetadata(
                moduleName,
                metadataFile.path,
                'describes a library with ${json.encode(lib)}, not an object',
              ),
            );
          }
          final importUri = lib['importUri'];
          if (importUri != null && importUri is! String) {
            throw DevToolException(
              _badMetadata(
                moduleName,
                metadataFile.path,
                'gives a library the import URI ${json.encode(importUri)}, '
                'not a string',
              ),
            );
          }
          if (importUri != null) libraryUris.add(importUri as String);
        }
        reloadEntry['libraries'] = libraryUris;
      }
    }

    if (withoutMetadata.isNotEmpty) {
      _logger.warning({
        'message': 'ddc_modules_without_metadata',
        'text':
            'Warning: the DDC compiler returned ${withoutMetadata.length} '
            'module(s) with no metadata (${withoutMetadata.join(', ')}). Hot '
            'reload identifies modules by the libraries in their metadata, so '
            'edits to those libraries will report as reloaded and will not '
            'take effect.',
        'modules': withoutMetadata,
        'dill': dillPath,
      });
    }

    // Only populate reloaded_sources.json after the first compile.
    // On initial load, it must be empty — DWDS's hot reload fetches it
    // and tries to reload every listed module. Matching Flutter's behavior.
    if (_initialCompileDone) {
      if (reloadedSources.isEmpty) {
        throw DevToolException(
          'The DDC compiler recompiled nothing for $dillPath: its manifest '
          '${manifestFile.path} names no modules.\n'
          'A recompile only happens here once something is known to have '
          'changed, so an empty result means the invalidated libraries never '
          'reached the compiler. `reloaded_sources.json` would list no '
          'modules, `\$dartReloadModifiedModules` would reload none, and the '
          'reload would report success while the page kept running the code '
          'it already had.',
        );
      }
      _reloadedSources = reloadedSources;
    } else {
      if (_modules.isEmpty) {
        throw DevToolException(
          'The first DDC compile of $dillPath produced no modules: its '
          'manifest ${manifestFile.path} is empty.\n'
          'The page loads its entrypoint and every module behind it from '
          'this server, so it would 404 its way to a blank screen.',
        );
      }
      _initialCompileDone = true;
    }
    _moduleDigests = digests;
  }

  /// The message for module metadata that is not the shape DDC emits.
  ///
  /// Every field here is read to build the module's `reloaded_sources.json`
  /// entry, which is how `$dartReloadModifiedModules` finds the libraries to
  /// reload. A bare `as` cast would report the same fault as a `TypeError`
  /// naming neither the module nor the file it came out of.
  static String _badMetadata(String module, String artifact, String fault) =>
      'The DDC metadata for module $module in $artifact $fault.\n'
      'DWDS reads the same bytes to map modules to libraries, so the debugger '
      'and hot reload cannot work from this compile.';

  /// The message for an artifact a successful compile said it wrote and did
  /// not. [role] says what the run loses with it, in the compiler's terms —
  /// "compile failed" would send the reader to their own source, and their
  /// source is not what is wrong.
  static String _missingArtifact(String path, String dillPath, String role) =>
      'The DDC compiler reported a successful compile of $dillPath but did '
      'not write $path — $role.\n'
      'Nothing from this compile can be served.';

  /// The bytes the manifest assigns to [section] of [module], checked against
  /// the artifact they index into.
  ///
  /// Every failure here means the compiler's manifest and its output disagree:
  /// a truncated artifact, or one left over from a different compile.
  static Uint8List _slice(
    Uint8List bytes, {
    required Map<String, dynamic> offsets,
    required String section,
    required String module,
    required String artifact,
  }) {
    final range = offsets[section];
    if (range is! List ||
        range.length != 2 ||
        range[0] is! int ||
        range[1] is! int) {
      throw DevToolException(
        'The DDC module manifest gives the $section of module $module as '
        '${json.encode(range)}, not a [start, end] byte range into '
        '$artifact.',
      );
    }
    final start = range[0] as int;
    final end = range[1] as int;
    if (start < 0 || end < start || end > bytes.length) {
      throw DevToolException(
        'The DDC module manifest puts the $section of module $module at '
        'bytes $start-$end of $artifact, which is ${bytes.length} bytes '
        'long. That artifact is truncated or is not the one this manifest '
        'describes.',
      );
    }
    return Uint8List.sublistView(bytes, start, end);
  }

  // ---- DWDS initialization ----

  /// Initialize DWDS for VM service protocol support.
  ///
  /// Must be called before [start] or after [start] with [chromeConnection]
  /// callback that will lazily connect to Chrome when DWDS needs it.
  ///
  /// Throws [DevToolException] when [packageConfigPath] is absent or cannot be
  /// read. DWDS resolves every `package:` URI through that config, so without
  /// it there is no VM service, no hot reload, no DevTools and no app console —
  /// the run is broken, not degraded. Returning with DWDS disabled instead
  /// produces a Chrome window that renders, reports `app.started`, and cannot
  /// be debugged or reloaded at all. `flutter run` has no code path that
  /// continues a debug web run with DWDS off either.
  /// [expressionCompiler] is what makes the debugger able to evaluate a Dart
  /// expression against the running app. Null is a real answer — DWDS then
  /// refuses each evaluation with its own message — and is what
  /// `--no-web-enable-expression-evaluation` asks for.
  Future<void> initDwds({
    required ConnectionProvider chromeConnection,
    Uri? serverUri,
    ExpressionCompiler? expressionCompiler,
  }) async {
    // Build the package URI mapper for DWDS module resolution.
    final configPath = packageConfigPath;
    if (configPath == null) {
      throw DevToolException(
        'Cannot start the web debugger: this run resolved no '
        'package_config.json, so DWDS has no way to map package: URIs to '
        'sources. Hot reload, DevTools and the app console all depend on '
        'it.',
      );
    }
    final PackageUriMapper mapper;
    try {
      mapper = PackageUriMapper(await pkg.loadPackageConfig(File(configPath)));
    } catch (e) {
      throw DevToolException(
        'Cannot start the web debugger: could not load the package config '
        'at $configPath: $e\n'
        'DWDS resolves every package: URI through it, so hot reload, '
        'DevTools and the app console would all be unavailable.',
      );
    }

    final strategyProvider = FrontendServerDdcLibraryBundleStrategyProvider(
      ReloadConfiguration.none,
      this, // AssetReader
      mapper,
      () async => _moduleDigests,
      BuildSettings(
        appEntrypoint: Uri.parse('org-dartlang-app:/$entrypointFilename'),
        canaryFeatures: true,
      ),
      packageConfigPath: packageConfigPath,
      reloadedSourcesUri: serverUri != null
          ? serverUri.replace(path: '/reloaded_sources.json')
          : Uri.parse('/reloaded_sources.json'),
    );

    _dwds = await Dwds.start(
      assetReader: this,
      buildResults: const Stream.empty(),
      chromeConnection: chromeConnection,
      toolConfiguration: ToolConfiguration(
        loadStrategy: strategyProvider.strategy,
        debugSettings: DebugSettings(
          expressionCompiler: expressionCompiler,
          // Off, unlike `flutter run`. The flag starts a second HTTP server
          // whose only client is the Dart Debug Extension — a browser
          // extension a user installs to debug a page some *other* tool
          // opened. This tool launches its own Chrome with a debugging port
          // and hands DWDS the connection, so nothing ever dials it.
          //
          // Leaving it on keeps `daemon.shutdown` from ending a web run:
          // `Dwds.stop()` closes its DevTools server, its dev handler and its
          // asset reader, but never the extension backend
          // (dart_web_debug_service.dart:52-56 — the backend is constructed in
          // `start` and handed to `DevHandler`, whose own `close` does not
          // touch it either). The listening socket outlives the teardown, and a
          // listening socket keeps the Dart VM alive, so the run answers
          // `{"message":"shutdown"}`, emits `app.stop`, and then sits there
          // until something kills it. `flutter run` gets away with the same
          // leak because flutter_tools ends every command with `exit()`.
          enableDebugExtension: false,
          // DWDS owns the Dart Development Service, the same arrangement
          // flutter_tools uses. Naming the Dart binary is what makes that
          // possible here: left to its own devices the launcher probes
          // `Platform.executable`, which under Bazel is this AOT binary, and
          // re-execs it as `<binary> development-service --vm-service-uri=…`.
          //
          // Owning it ourselves instead would cost more than the subprocess:
          // DWDS registers `hotRestart` and `fullReload` against its DDS, so
          // with no DDS of its own those land in a local registry that
          // DevTools cannot see.
          ddsConfiguration: DartDevelopmentServiceConfiguration(
            enable: true,
            serveDevTools: true,
            dartExecutable: dartExecutable,
          ),
        ),
        // The hostname the page is served from, not a constant: with
        // `--web-hostname` the injected DWDS client dials this back, and a
        // hardcoded `localhost` is a flag honoured by the bind and silently
        // dropped by the debugger.
        appMetadata: AppMetadata(hostname: options.displayHost),
      ),
    );

    // Swap the active handler to include DWDS middleware.
    // Match Flutter's web_asset_server.dart:387-393 composition:
    // DWDS middleware wraps only our asset handler (not DWDS's own handler).
    // Cascade tries DWDS handler first, then our wrapped asset handler.
    final wrappedAssetHandler = const shelf.Pipeline()
        .addMiddleware(_dwds!.middleware)
        .addHandler(_shelfHandler);
    _activeHandler = shelf.Cascade()
        .add(_dwds!.handler)
        .add(wrappedAssetHandler)
        .handler;
  }

  // ---- HTTP server ----

  /// The current request handler — swapped when DWDS is initialized.
  late shelf.Handler _activeHandler = _shelfHandler;

  /// Start the HTTP server.
  ///
  /// Call [initDwds] after this to integrate DWDS middleware —
  /// the handler is swapped in-place without restarting the server.
  ///
  /// Throws [DevToolException] when either half of the boot path is missing:
  /// the build's `flutter_bootstrap.js`, or the `flutter.js` it loads out of
  /// [buildOutputDir]. Every page this server serves boots through both, so
  /// without either the browser opens on a blank page. Checked here, before a
  /// browser is launched, the run ends naming the file instead.
  Future<Uri> start() async {
    if (!File(flutterBootstrapJsPath).existsSync()) {
      throw DevToolException(
        _noBootstrap('$flutterBootstrapJsPath does not exist'),
      );
    }
    if (!File(_flutterJsPath).existsSync()) {
      throw DevToolException(_noFlutterJs('$_flutterJsPath does not exist'));
    }

    // Use an indirection so we can swap the handler after DWDS init.
    _server = await bindWebServer(
      options,
      (request) => _activeHandler(request),
    );
    return uri!;
  }

  /// Stop the HTTP server and DWDS.
  Future<void> stop() async {
    await _dwds?.stop();
    _dwds = null;
    await _server?.close();
    _server = null;
  }

  /// Where `flutter.js` lives in the build output.
  String get _flutterJsPath => p.join(buildOutputDir, 'flutter.js');

  /// The bootstrap the build substituted for this dev loop.
  ///
  /// Read per request, and by name rather than through the static handler: a
  /// 404 for this path renders as a blank page and would say so nowhere, while
  /// a named failure reaches both the log and the 500 body. [start] has already
  /// established that the file exists, so this fails only if it goes away
  /// mid-run — a rebuild replacing the output tree, say.
  String _readBootstrap() {
    try {
      return File(flutterBootstrapJsPath).readAsStringSync();
    } on FileSystemException catch (e) {
      throw DevToolException(
        _noBootstrap(
          '$flutterBootstrapJsPath could not be read: ${e.osError ?? e}',
        ),
      );
    }
  }

  /// Why a run with no readable bootstrap cannot show anything.
  static String _noBootstrap(String cause) =>
      'Cannot serve flutter_bootstrap.js: $cause.\n'
      'The build substitutes that file from the target\'s bootstrap template; '
      'it is the whole boot path, so the page would load and stay blank.';

  /// Why a run with no `flutter.js` cannot show anything.
  static String _noFlutterJs(String cause) =>
      'Cannot serve flutter.js: $cause.\n'
      'flutter_bootstrap.js loads flutter.js to boot the engine, so the page '
      'would load and stay blank.';

  /// The generated scripts that carry a page from `flutter.js` to a running
  /// program.
  ///
  /// Held as one set, and answered ahead of every other arm of the request
  /// cascade, because whether they may be served *at all* is a single
  /// decision. The cascade's last arm serves whatever it finds in
  /// [buildOutputDir], and `main.dart.js` is a real name in a release bundle
  /// — so a gate that declined to answer rather than returning would hand the
  /// browser a compiled page that renders correctly with no dev loop behind
  /// it, which is a worse failure than the one being fixed.
  static const _bootChain = {
    'main.dart.js',
    'main_module.bootstrap.js',
    'on_load_end_bootstrap.js',
  };

  /// The boot chain's answer, or null when [path] is not part of it.
  ///
  /// Refused until [holdsProgram]. DWDS injects its client into
  /// `main_module.bootstrap.js`, at the marker the generated body opens with
  /// (dwds `handlers/injector.dart`) — so serving the boot chain before any
  /// compile is precisely what lets a debugger client attach to a page that
  /// has no program. That is the state where `hotRestart` answers "Successful
  /// hot restart" having done nothing, and a hot reload injects a delta into a
  /// blank page and reports it applied.
  /// Withholding the scripts makes the state unreachable instead of leaving
  /// it to be detected afterwards.
  ///
  /// `no-store` on both answers, because `--web-port` pins the origin across
  /// runs: either a stale refusal or a stale program could otherwise outlive
  /// the state that produced it.
  shelf.Response? _serveBootChain(String path) {
    if (!_bootChain.contains(path)) {
      return null;
    }
    const noStore = 'no-store';
    if (!holdsProgram) {
      return shelf.Response(
        HttpStatus.serviceUnavailable,
        body:
            'The dev server holds no program yet, so it will not serve '
            '$path.\n'
            'The page boots through this script, so serving it now would '
            'attach a debugger to a page with nothing to run. This clears '
            'as soon as a compile lands. If it does not, the first compile '
            'is failing and its errors are on the tool\'s output.',
        headers: {'content-type': 'text/plain', 'cache-control': noStore},
      );
    }
    final headers = {
      'content-type': contentTypeFor(path),
      'cache-control': noStore,
    };
    switch (path) {
      case 'main.dart.js':
        // Cached: the inputs never change within a run.
        _ddcBootstrapJs ??= generateDDCBootstrapScript(
          entrypoint: entrypointFilename,
        );
        return shelf.Response.ok(_ddcBootstrapJs, headers: headers);
      case 'main_module.bootstrap.js':
        _ddcMainModuleJs ??= generateDDCMainModuleScript(
          entrypoint: entrypointFilename,
          nativeNullAssertions: nativeNullAssertions,
        );
        return shelf.Response.ok(_ddcMainModuleJs, headers: headers);
      default:
        return shelf.Response.ok(generateOnLoadEndScript(), headers: headers);
    }
  }

  /// Shelf handler for all asset requests.
  Future<shelf.Response> _shelfHandler(shelf.Request request) async {
    final path = request.url.path.isEmpty ? 'index.html' : request.url.path;

    try {
      // 0. The boot chain, before anything else can answer for it.
      final bootChain = _serveBootChain(path);
      if (bootChain != null) {
        return bootChain;
      }

      // 1. In-memory files (first-upload bootstrap files override everything).
      if (_files.containsKey(path)) {
        return shelf.Response.ok(
          _files[path]!,
          headers: {'content-type': contentTypeFor(path)},
        );
      }

      // 2. flutter_bootstrap.js — the build's, substituted for the dev loop.
      if (path == 'flutter_bootstrap.js') {
        return shelf.Response.ok(
          _readBootstrap(),
          headers: {'content-type': contentTypeFor(path)},
        );
      }

      // 3. DDC modules from memory.
      if (_modules.containsKey(path)) {
        return shelf.Response.ok(
          _modules[path]!,
          headers: {'content-type': contentTypeFor(path)},
        );
      }

      // Source maps from memory.
      if (_sourcemaps.containsKey(path)) {
        return shelf.Response.ok(
          _sourcemaps[path]!,
          headers: {'content-type': contentTypeFor(path)},
        );
      }

      // 4. reloaded_sources.json for hot reload/restart.
      if (path == 'reloaded_sources.json') {
        return shelf.Response.ok(
          json.encode(_reloadedSources ?? []),
          headers: {'content-type': contentTypeFor(path)},
        );
      }

      // 6. dart_sdk.js from DDC build outputs.
      if (path == 'dart_sdk.js') {
        return _serveFile(webToolchain.dartSdkJs);
      }
      if (path == 'dart_sdk.js.map') {
        final mapPath = '${webToolchain.dartSdkJs}.map';
        if (File(mapPath).existsSync()) {
          return _serveFile(mapPath);
        }
      }

      // 7. DDC module loader + stack trace mapper from DDC build outputs.
      if (path == 'ddc_module_loader.js') {
        return _serveFile(webToolchain.ddcModuleLoaderJs);
      }
      if (path == 'stack_trace_mapper.js') {
        return _serveFile(webToolchain.stackTraceMapperJs);
      }

      // 8. Metadata files for DWDS.
      if (_metadata.containsKey(path)) {
        return shelf.Response.ok(
          _metadata[path]!,
          headers: {'content-type': contentTypeFor(path)},
        );
      }

      // 9. Static files from build output directory. The path came off the
      // wire, so it is served contained within the bundle.
      return serveFileWithin(buildOutputDir, path);
    } catch (e, stack) {
      // The 500 stays: one request failing is not grounds to end a run, and
      // upstream serves on through the same failure (`web_asset_server.dart:
      // 400-406` logs and keeps serving). What it is grounds for is saying so
      // — the browser is the only party that knows, and it reports a failed
      // asset as a blank page.
      _logger.severe(
        {
          'message': 'asset_request_failed',
          'text': 'Error serving /$path: $e',
          'path': path,
          'error': '$e',
        },
        e,
        stack,
      );
      return shelf.Response.internalServerError(body: 'Error: $e');
    }
  }
