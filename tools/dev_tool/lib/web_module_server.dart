/// Where this file's warnings and errors go.
///
/// Through the logger rather than straight to stderr so a `LOG_FORMAT=json`
/// consumer gets records it can parse, like every other diagnostic the tool
/// emits.
final _logger = Logger('dev_tool.web_module_server');

/// The one MIME table for everything the web dev loop serves.
///
/// Both [WebModuleServer] (DDC dev mode) and [StaticWebServer] (WASM /
/// production JS mode) answer from this table, so a file can never be typed
/// differently depending on which mode served it — a script typed
/// `application/octet-stream` by one route is a script the browser refuses
/// to execute, and the failure looks like a bug in the app.
///
/// Every entry is a type observed in real build output or generated by this
/// tool. `map` and `metadata` are the DDC compiler's source maps and module
/// metadata — JSON the debugger reads. Extensions absent from the table are
/// served as `application/octet-stream` deliberately, not as an accident of
/// a missed case: everything else a built bundle contains (`.bin` asset
/// manifests, `.frag` shaders, `.symbols`, `NOTICES.Z`) is fetched by the
/// engine, which never inspects the type. The types the browser *does*
/// enforce — scripts, wasm, html, css, fonts — are all named.
String contentTypeFor(String path) {
  final ext = p.extension(path).replaceFirst('.', '');
  return switch (ext) {
    'html' => 'text/html',
    'js' || 'mjs' => 'application/javascript',
    'wasm' => 'application/wasm',
    'json' => 'application/json',
    'css' => 'text/css',
    'png' => 'image/png',
    'ico' => 'image/x-icon',
    'otf' => 'font/otf',
    'txt' => 'text/plain',
    'map' || 'metadata' => 'application/json',
    _ => 'application/octet-stream',
  };
}

/// How many ephemeral ports a wildcard may draw before giving up.
///
/// `HttpMultiServer._loopback`'s own number, for the same search: it re-draws
/// up to five times when a port turns out to be free on one loopback family
/// and held on the other. Five consecutive intercepted draws is not bad luck —
/// it means something on this host is answering across the ephemeral range —
/// and that is when saying so is the useful answer.
const _maxPortDraws = 5;

/// Bind the one HTTP server both web servers serve from.
///
/// The response headers are set on the server's `defaultResponseHeaders`
/// rather than by shelf middleware, which is what upstream does
/// (`web_asset_server.dart`) and is the stronger of the two mechanisms here:
///
///  * Only defaults can *remove* a header dart:io adds by itself. dart:io
///    sends `X-Frame-Options: SAMEORIGIN` on every response, which forbids
///    embedding the app in an iframe; upstream removes it and so does this.
///    Middleware could never have taken it off.
///  * shelf writes a response's own headers with `set`, so they overwrite
///    these defaults key by key. A `--web-header Content-Type=…` therefore
///    cannot retype an asset out from under the browser, where middleware
///    applied after the handler would have.
///  * shelf's own 500 for a handler that threw never passes through
///    middleware, and does carry the defaults.
///
/// A named `--web-port` that cannot be taken is reported with the port in it,
/// because the whole point of naming a port is that something else is expected
/// to find the server there. Moving onto a different port would answer a
/// question nobody asked. `--web-port 0` is the opposite question — "any free
/// port" — and is searched for, up to [_maxPortDraws] draws.
Future<HttpServer> bindWebServer(
  WebServerOptions options,
  shelf.Handler handler,
) async {
  // A named port is one draw: it never moves, because something is expected to
  // find the server where it was named. `--web-port 0` is a search — "any free
  // port" — and a port whose traffic the kernel hands to somebody else is not
  // free. `HttpMultiServer._loopback` searches the same way for the same
  // reason, one family over; the only difference here is where the collision
  // becomes visible, since a wildcard bind cannot be refused.
  final draws = options.port == 0 ? _maxPortDraws : 1;
  for (var draw = 1; ; draw++) {
    try {
      return await _bindOneServer(options, handler);
    } on _InterceptedPort catch (e) {
      if (draw == draws) throw DevToolException(e.explain(options, draws));
    }
  }
}

/// One attempt: bind, dress, and — for a wildcard — confirm it is reached.
///
/// Throws [_InterceptedPort] when the port this bound is one it does not own;
/// every other failure throws what it is.
Future<HttpServer> _bindOneServer(
  WebServerOptions options,
  shelf.Handler handler,
) async {
  final HttpServer server;
  try {
    server = await _bindEveryAddressOfTheHost(options);
  } on SocketException catch (e) {
    throw DevToolException(
      'Cannot serve the app on ${options.hostname}:${options.port}: '
      '${e.osError ?? e}.\n'
      '${options.port == 0 ? 'No port could be bound at all, which is a '
                'problem with this host rather than with the run.' : 'Free port '
                '${options.port}, or pass a different --web-port. Nothing else '
                'is chosen for you: something is expected to find the server '
                'where you named it.'}',
    );
  }

  // Anything past this point owns the bound socket: a throw here has to give
  // it back, or the port stays held by a server nobody has a handle to — and
  // with `--web-port` that is the one port the next attempt needs.
  try {
    // dart:io's own default, and the reason a Flutter web app served by this
    // tool could not be embedded in an iframe. Removed as upstream removes
    // it. A run that wants it back can say so: `--web-header
    // X-Frame-Options=SAMEORIGIN`.
    server.defaultResponseHeaders.remove('x-frame-options', 'SAMEORIGIN');
    if (options.crossOriginIsolation) {
      crossOriginIsolationHeaders.forEach(server.defaultResponseHeaders.set);
    }
    // Last, so a `--web-header` naming something this tool also sets is the
    // one that survives — except the isolation headers, which
    // `WebOptions.resolve` refuses outright rather than letting either side
    // win quietly.
    options.headers.forEach((name, value) {
      try {
        server.defaultResponseHeaders.set(name, value);
      } catch (e) {
        // `dart:io` validates several header names and values itself — a
        // malformed `Date`, an illegal character in a name. Reported with the
        // flag and the pair in it; the raw HttpException names neither.
        throw DevToolException(
          'Cannot serve with --web-header $name=$value: $e',
        );
      }
    });
    // A wildcard bind is the one bind that can succeed without owning the
    // port, so it is the one that has to be asked. Every other hostname here
    // binds a specific address, and a specific address already held is a bind
    // the kernel refuses on every platform this runs on. There is nothing left
    // for a check to find there, and a check that no test can make fail is not
    // a check.
    if (options.hostname == anyHostname) {
      final probe = _ReachabilityProbe();
      shelf_io.serveRequests(server, probe.wrap(handler));
      await probe.confirmThisServerIsReached(options, server);
    } else {
      shelf_io.serveRequests(server, handler);
    }
  } catch (_) {
    await server.close(force: true);
    rethrow;
  }

  return server;
}

/// A request only this server can answer, used to confirm it is the server the
/// published URL actually reaches.
///
/// `--web-hostname any` binds a wildcard, and a wildcard bind is allowed to
/// succeed on a port another process already holds on one *specific* address.
/// The kernel then routes every connection to that address to the more
/// specific socket, so this server starts, prints its URL, and never receives
/// a request — with not even a failed bind to say so. That is not hypothetical:
/// `adb` keeps dozens of listening sockets on 127.0.0.1 in the ephemeral range,
/// and answers a connection by closing it without a byte.
///
/// Nothing about the bind can reveal that, so the server is asked instead: one
/// request per address the published URL resolves to, for a path only this
/// instance knows. Whatever else might hold the port can accept the connection
/// and can answer 200 — it cannot produce the nonce.
///
/// A failure here is what a `--web-port 0` run answers by drawing another
/// port, which is the same search `HttpMultiServer._loopback` runs for
/// `localhost`. A *named* port never moves; it fails naming itself.
///
/// What this proves is bounded, deliberately: it is the state at startup. A
/// process that takes a specific address on this port *later* still wins the
/// traffic from then on, and no arrangement of binds available here prevents
/// that — holding the specific addresses alongside the wildcard is refused
/// outright by Linux, which is the platform where the whole interception is
/// impossible anyway.
class _ReachabilityProbe {
  /// The path this instance answers, random so that nothing else listening on
  /// the port can answer it by coincidence and no bundle asset is shadowed by
  /// it. Answered only while the check is running.
  static final _random = Random.secure();
  final String _nonce = List.generate(
    16,
    (_) => _random.nextInt(256).toRadixString(16).padLeft(2, '0'),
  ).join();

  bool _answering = true;

  /// [inner] with this instance's one reserved path in front of it.
  shelf.Handler wrap(shelf.Handler inner) => (shelf.Request request) {
    if (_answering && request.url.path == _nonce) {
      return shelf.Response.ok(_nonce);
    }
    return inner(request);
  };

  /// Throw unless every address the published URL names reaches this server.
  ///
  /// Every address it names, with none dropped for belonging to a family this
  /// server did not bind. What this server binds is decided by a ::1 *bind*
  /// (`HttpMultiServer.supportsIPv6` picks the IPv4 wildcard when that fails),
  /// while what this check dials is decided by the *resolver* — two different
  /// tests, which a host could in principle answer differently. On every
  /// platform this runs on, none does:
  ///
  ///  * macOS: ::1 binds, so `any` is the dual-stack `::` wildcard, which
  ///    carries IPv4 too. The IPv4 wildcard is never the one chosen.
  ///  * Linux with no IPv6: the resolver has already dropped the family —
  ///    `InternetAddress.lookup('localhost')` returns 127.0.0.1 alone, so
  ///    there is nothing for a filter to remove.
  ///  * Windows: ::1 binds even with IPv6 disabled as far as Windows allows,
  ///    because ::1 stays on the loopback pseudo-interface regardless — so the
  ///    IPv4 wildcard is not chosen there either, and in that state the
  ///    resolver returns 127.0.0.1 alone exactly as Linux does.
  ///
  /// `getaddrinfo` does not agree with itself across languages: `python3`'s,
  /// called with `flags=0`, returns both families on a Linux host where Dart
  /// returns one. Dart matches the `AI_ADDRCONFIG`-filtered answer.
  Future<void> confirmThisServerIsReached(
    WebServerOptions options,
    HttpServer server,
  ) async {
    final port = server.port;
    final published = options.baseUri(port);
    // `displayHost` and not `hostname`: `any` is not a name anything resolves,
    // and the URL this run prints and opens a browser on says `localhost`.
    // That name is the promise being checked.
    final resolved = await InternetAddress.lookup(options.displayHost);
    for (final address in resolved) {
      final String answer;
      try {
        answer = await _fetch(
          published.replace(host: address.address, path: '/$_nonce'),
          options,
        );
      } catch (e) {
        throw _InterceptedPort(port, address, 'the request failed: $e');
      }
      if (answer != _nonce) {
        throw _InterceptedPort(port, address, 'something else answered it');
      }
    }
    _answering = false;
  }

  /// GET [url] and read it to the end.
  ///
  /// A self-signed certificate is accepted here: this run generated it, and
  /// the nonce — which no interloper can produce — is what identifies the
  /// server, not the certificate.
  Future<String> _fetch(Uri url, WebServerOptions options) async {
    final client = HttpClient();
    if (options.isSecure) {
      client.badCertificateCallback = (_, __, ___) => true;
    }
    try {
      final response = await (await client.getUrl(url)).close();
      return await response.transform(utf8.decoder).join();
    } finally {
      client.close(force: true);
    }
  }
}

/// A port a wildcard bind took and does not own.
///
/// Its own type rather than a [DevToolException] because it is the one failure
/// a `--web-port 0` run answers by drawing again: everything else that can go
/// wrong between bind and serve — an unusable certificate, a header `dart:io`
/// refuses — fails the same way on every port, and retrying it would report
/// the wrong cause five draws later.
class _InterceptedPort implements Exception {
  final int port;
  final InternetAddress address;

  /// What the server saw when it asked for itself.
  final String observed;

  const _InterceptedPort(this.port, this.address, this.observed);

  /// Why this run cannot be served, after [draws] of them.
  String explain(WebServerOptions options, int draws) =>
      'Cannot serve the app on --web-hostname $anyHostname: this run bound '
      'port $port on every interface, but ${options.baseUri(port)} over '
      '${address.address} does not reach it — $observed.\n'
      'Either something else already holds that port on that address — a '
      'wildcard bind is allowed to sit alongside a more specific listener, and '
      'the kernel hands that listener the connection — or nothing this run '
      'bound is listening there. Neither shows up as a failed bind, so this '
      'server would have started, printed its URL and never received a '
      'request.\n'
      '${draws == 1 ? 'Free port $port, or pass a different --web-port. '
                'Nothing else is chosen for you: something is expected to find the '
                'server where you named it.' : 'All $draws ports this run drew went '
                'the same way, so this is not one unlucky port: something on this '
                'host is answering across the ephemeral range. Name a port it does '
                'not hold with --web-port.'}';
}

/// Bind every socket the host in [options] stands for.
///
/// The URL this server publishes names a *host*, and `localhost` is not one
/// address: it is 127.0.0.1 and ::1. A client resolving that name chooses
/// between the two families itself, so a server that binds one of them is
/// reachable by only half its own URL — and the other half belongs to whatever
/// else on the machine happens to hold that port number on the family this
/// server left free.
///
/// That is how a dev run gets silently intercepted. `adb` keeps dozens of
/// listening sockets on 127.0.0.1 in the ephemeral range, roughly one port in
/// every four hundred. A server bound to ::1 that draws one of those numbers
/// hands every `localhost` client that picks IPv4 — Chrome included — to adb,
/// which accepts the connection and closes it without a byte. The page never
/// loads, and the DDC dev loop treats a browser that has not connected *yet* as
/// normal, so nothing reports it.
///
/// So the loopback is bound on both families, through the package the Dart
/// ecosystem's servers use for it. With `--web-port 0` that means searching
/// for a port free on both, which is what makes a collision a non-event; a
/// *named* port still fails naming it, including in the case that otherwise
/// looks like success — the port held on one family only.
///
/// [anyHostname] binds one dual-stack wildcard, covering both families for the
/// same reason the loopback does — the URL it publishes says `localhost`
/// ([WebServerOptions.displayHost]), because `any` is not a name a browser
/// resolves. Binding `0.0.0.0` would leave ::1 — half of its own URL — to
/// whatever else wanted it, which is the loopback defect one family over.
///
/// That is a deliberate widening of the flag: `any` answers on every
/// address of every interface rather than every IPv4 address, matching what
/// `flutter run` binds for the same flag and what the Dart ecosystem's servers
/// mean by "any". The exposure the flag already carries — the app and its
/// sources, on every network this host is attached to — is the same set of
/// networks, reached over both families instead of one.
///
/// One socket rather than a wildcard plus the specific loopbacks, which would
/// let the kernel refuse a squatted port at bind time: holding a specific
/// address alongside a wildcard on one port is permitted by BSD and refused
/// outright by Linux, so it cannot be what this does. What the wildcard cannot
/// learn at bind time, [_ReachabilityProbe] asks for after it.
///
/// Any other hostname binds the one address it resolves to: unambiguous when
/// it is written as an address, and carrying the same exposure when it is a
/// name with more than one behind it.
Future<HttpServer> _bindEveryAddressOfTheHost(WebServerOptions options) async {
  final context = options.isSecure ? _securityContext(options) : null;

  if (options.hostname == defaultHostname || options.hostname == anyHostname) {
    // `HttpMultiServer` reads both names itself: `localhost` is the pair of
    // loopback addresses, `any` is the dual-stack wildcard where the host has
    // IPv6 and the IPv4 one where it does not.
    return context == null
        ? HttpMultiServer.bind(options.hostname, options.port)
        : HttpMultiServer.bindSecure(options.hostname, options.port, context);
  }

  final InternetAddress address;
  try {
    address = (await InternetAddress.lookup(options.hostname)).first;
  } on SocketException catch (e) {
    throw DevToolException(
      'Cannot serve the app on --web-hostname ${options.hostname}: that '
      'name does not resolve on this host (${e.osError ?? e}).\n'
      'Use an address this machine has, or "any" for every interface.',
    );
  }
  return context == null
      ? HttpServer.bind(address, options.port)
      : HttpServer.bindSecure(address, options.port, context);
}

/// The TLS context for a server [options] says is secure.
///
/// Both paths are read here rather than at bind time so an unreadable
/// certificate is reported as one. `bindSecure` would otherwise surface it as
/// a bare `TlsException` or `FileSystemException` naming neither flag.
SecurityContext _securityContext(WebServerOptions options) {
  final context = SecurityContext();
  try {
    context.useCertificateChain(options.tlsCertPath!);
  } catch (e) {
    throw DevToolException(
      'Cannot serve over TLS: --web-tls-cert-path '
      '${options.tlsCertPath} could not be used as a certificate chain '
      '($e).',
    );
  }
  try {
    context.usePrivateKey(options.tlsCertKeyPath!);
  } catch (e) {
    throw DevToolException(
      'Cannot serve over TLS: --web-tls-cert-key-path '
      '${options.tlsCertKeyPath} could not be used as the private key for '
      '${options.tlsCertPath} ($e).',
    );
  }
  return context;
}

/// Serve the file at [requestPath] resolved inside [root].
///
/// 404 for a file that is not there — and for a path that resolves outside
/// [root], which no legitimate page request produces. `dart:io`'s HTTP
/// server already collapses `..` segments (encoded or not) before a handler
/// runs, so today no wire request can reach the check; it states the
/// contract explicitly rather than inheriting it from transport behavior.
shelf.Response serveFileWithin(String root, String requestPath) {
  final filePath = p.normalize(p.join(root, requestPath));
  if (!p.isWithin(root, filePath)) {
    return shelf.Response.notFound('File not found: $requestPath');
  }
  return _serveFile(filePath);
}

/// Serve the file at [filePath], typed from the one MIME table.
shelf.Response _serveFile(String filePath) {
  final file = File(filePath);
  if (!file.existsSync()) {
    return shelf.Response.notFound('File not found: $filePath');
  }
  return shelf.Response.ok(
    file.openRead(),
    headers: {'content-type': contentTypeFor(filePath)},
  );
}

/// Serves a built web bundle directory — WASM and production JS mode.
///
/// The static counterpart of [WebModuleServer]: no DWDS, no modules, just the
/// files the build wrote. Same MIME table ([contentTypeFor]) and same
/// isolation headers ([crossOriginIsolation]), by construction.
class StaticWebServer {
  /// The bundle directory to serve (e.g. `bazel-bin/app_wasm_web/`).
  final String rootPath;

  /// Where to bind, what to serve it over, and what headers to add. The same
  /// value the DDC module server is built from, so a serving flag cannot mean
  /// one thing for a DDC run and nothing at all for a WASM one.
  final WebServerOptions options;

  HttpServer? _server;

  StaticWebServer({required this.rootPath, required this.options});

  /// The underlying HTTP server, once started.
  ///
  /// Exposed so a launch can hand it to the instance that owns its lifetime.
  HttpServer? get server => _server;

  /// The base URL of the running server.
  Uri? get uri => _server == null ? null : options.baseUri(_server!.port);

  /// Bind where [options] say and start serving.
  Future<Uri> start() async {
    _server = await bindWebServer(options, _handle);
    return uri!;
  }

  /// Stop the HTTP server.
  Future<void> stop() async {
    await _server?.close();
    _server = null;
  }

  shelf.Response _handle(shelf.Request request) {
    final path = request.url.path.isEmpty ? 'index.html' : request.url.path;
    return serveFileWithin(rootPath, path);
  }
}

/// Serves DDC-compiled modules and static assets for web dev mode.
///
/// Implements [AssetReader] so DWDS can resolve sources, source maps,
/// and metadata for debugging and hot reload.
class WebModuleServer implements AssetReader {
  final WebToolchainPaths webToolchain;

  /// The build output directory (e.g. `bazel-bin/app_wasm_web/`).
  final String buildOutputDir;

  /// The synthetic entrypoint filename (just `main.dart`, not a full path).
  final String entrypointFilename;

  /// The file served at `/flutter_bootstrap.js`, from the build's dev config.
  ///
  /// The build substitutes this target's `bootstrap_js` template with the DDC
  /// build config a dev run compiles under — so a page booted here runs the
  /// same loader the bundle ships, carrying the same `web_defines`, against
  /// DDC's output instead of dart2wasm's. Read per request rather than cached:
  /// a `--watch` rebuild rewrites it when the template or a define changes,
  /// and the built index.html beside it is served from disk the same way.
  final String flutterBootstrapJsPath;

  /// Workspace root (for dart source lookups by DWDS).
  final String? workspaceRoot;

  /// Path to package_config.json (for DWDS package URI resolution).
  final String? packageConfigPath;

  /// Dart binary from the Flutter toolchain. DWDS launches its Dart
  /// Development Service with it rather than probing `Platform.executable`,
  /// which under Bazel is this AOT binary and cannot serve as a Dart SDK.
  final String dartExecutable;

  /// DDC's `nativeNonNullAsserts`, as the build set it.
  ///
  /// The dev loop generates `main_module.bootstrap.js` itself rather than
  /// serving the build's, so this is the one place the build's answer can
  /// reach the page.
  final bool nativeNullAssertions;

  /// Where to bind, what to serve it over, and what headers to add.
  final WebServerOptions options;

  /// Cached parsed package config for source resolution.
  pkg.PackageConfig? _packageConfig;

  /// Server paths whose source lookup already failed and was reported.
  ///
  /// DWDS asks for the same source on every debugger view, and the conditions
  /// that break a lookup — an unreadable package config, chiefly — break every
  /// one of them. Said once per path, the warning stays readable.
  final Set<String> _reportedSourceFailures = {};

  /// Compiled JS modules keyed by URL path.
  final Map<String, Uint8List> _modules = {};

  /// Source maps keyed by URL path (e.g. `foo.lib.js.map`).
  final Map<String, Uint8List> _sourcemaps = {};

  /// Module metadata keyed by URL path (e.g. `foo.lib.js.metadata`).
  final Map<String, Uint8List> _metadata = {};

  /// In-memory file storage for first-upload bootstrap files.
  /// These override build-output files and generated scripts.
  final Map<String, Uint8List> _files = {};

  /// Reloaded module descriptors for `reloaded_sources.json`.
  /// Each entry has `src`, `module`, and optionally `libraries`.
  List<Map<String, dynamic>>? _reloadedSources;

  /// Module metadata for DWDS's `MetadataProvider`, keyed by module path.
  ///
  /// A map rather than a joined string: DWDS re-reads this artifact on EVERY
  /// bootstrap request — it replaces its provider per request (dwds
  /// `strategy.dart:179-181`) and embeds the module list it derives into the
  /// served body (`_ddcLoaderSetup`, `ddc_library_bundle.dart:189-224`). The
  /// DDC loader then loads exactly that list and nothing else.
  ///
  /// So this is not bookkeeping; it is what a fresh page boots from. Held
  /// whole, it survives an incremental compile the way [_modules] and
  /// [_metadata] beside it already do. Replaced wholesale, one hot reload
  /// leaves it describing a single module, and the next page load boots
  /// nothing but that one.
  final Map<String, String> _metadataByModule = {};

  /// Module digests: module name → hash.
  Map<String, String> _moduleDigests = {};

  /// Whether the first compile has completed. Used to skip populating
  /// reloaded_sources.json on initial compile (matching Flutter).
  bool _initialCompileDone = false;

  /// Whether a compile has landed, so this server has a program to hand out.
  ///
  /// False between startup and the first successful compile — a window that
  /// only exists because a failed *first* compile does not end the run (see
  /// `web_pipeline_assembler.dart`). Upstream `flutter run` has no such
  /// window: a failed first compile returns before Chrome is launched
  /// (`resident_web_runner.dart:334-339`, launch at :367), so no browser ever
  /// reaches its server in this state. We launch Chrome anyway, which is what
  /// makes the window reachable and why [_serveBootChain] exists.
  ///
  /// This is a fact about the *server*, and the only thing that should be
  /// asked of it. What the page holds is a different fact, and the two must not
  /// be conflated: "a compile finished" is not "the page got something".
  bool get holdsProgram => _initialCompileDone;

  /// Cached DDC bootstrap scripts (generated once, served on every request).
