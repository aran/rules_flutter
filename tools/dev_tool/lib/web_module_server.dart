  @override
  Future<String?> dartSourceContents(String serverPath) async {
    // Check in-memory files first.
    final bytes = _files[serverPath];
    if (bytes != null) return utf8.decode(bytes);
    // Read from workspace filesystem.
    if (workspaceRoot != null && serverPath.endsWith('.dart')) {
      final file = File(p.join(workspaceRoot!, serverPath));
      if (file.existsSync()) return file.readAsStringSync();
      // Try packages/ → package: resolution via package_config.
      if (serverPath.startsWith('packages/') && packageConfigPath != null) {
        try {
          _packageConfig ??= await pkg.loadPackageConfig(
            File(packageConfigPath!),
          );
          final packagePath = serverPath.replaceFirst('packages/', 'package:');
          final resolved = _packageConfig!.resolve(Uri.parse(packagePath));
          if (resolved != null) {
            final source = File(resolved.toFilePath());
            if (source.existsSync()) return source.readAsStringSync();
          }
        } catch (e) {
          // A source we cannot resolve is a null to DWDS and a blank pane in
          // the debugger. `null` is the honest answer for a file that is
          // simply not there — but not for a lookup that *failed*.
          if (_reportedSourceFailures.add(serverPath)) {
            _logger.warning({
              'message': 'dart_source_lookup_failed',
              'text':
                  'Warning: could not resolve the Dart source for '
                  '$serverPath through $packageConfigPath: $e. The debugger '
                  'will show no source for it.',
              'path': serverPath,
              'packageConfig': packageConfigPath,
              'error': '$e',
            });
          }
        }
      }
    }
    return null;
  }

  @override
  Future<String?> sourceMapContents(String serverPath) async {
    var path = serverPath;
    if (path.startsWith('/')) path = path.substring(1);
    // Source maps are looked up by their .js path (strip .map).
    if (path.endsWith('.map')) {
      final bytes = _sourcemaps[path];
      if (bytes != null) return utf8.decode(bytes);
    }
    return null;
  }

  @override
  Future<String?> metadataContents(String serverPath) async {
    final path = serverPath.startsWith('/')
        ? serverPath.substring(1)
        : serverPath;
    // DWDS MetadataProvider asks for `main_module.ddc_merged_metadata`.
    if (path == 'main_module.ddc_merged_metadata' &&
        _metadataByModule.isNotEmpty) {
      return _metadataByModule.values.join('\n');
    }
    // Try exact path match in metadata store.
    final bytes = _metadata[path];
    if (bytes != null) return utf8.decode(bytes);
    return null;
  }

